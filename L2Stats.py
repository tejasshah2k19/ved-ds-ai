import numpy as np 

reliance = [52,33,96,52,74,85,63]

#max 
print("Max = ",np.max(reliance))

#min 
print("Min = ",np.min(reliance))


#avg 
print("Median = ",np.median(reliance))
print("Avg = ",np.average(reliance))


#sum 
print("Sum = ",np.sum(reliance))

#argmax argmin
print("max index : ",np.argmax(reliance))


